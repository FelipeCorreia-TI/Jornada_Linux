#!/bin/bash

# ==========================================
# LINUX BASH - LOCOMOÇÃO ENTRE DIRETÓRIOS
# ==========================================

# ls
# Lista arquivos e diretórios do local atual.
ls

# pwd
# Mostra o caminho completo do diretório atual.
pwd

# cd
# Entra em outro diretório.
cd nome_da_pasta

# Caminho absoluto
# Começa na raiz do sistema (/).
cd /home/usuario/documentos

# Caminho relativo
# Usa o diretório atual como referência.
cd ../

# Sobe um nível de diretório.
cd ..

# Sobe dois níveis.
cd ../..

# ==========================================
# DICA:
# .  = diretório atual
# .. = diretório anterior
# /  = separador de diretórios
# ==========================================