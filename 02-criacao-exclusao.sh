#!/bin/bash

# ==========================================
# LINUX BASH - CRIAÇÃO E EXCLUSÃO
# ==========================================

# mkdir
# Cria um novo diretório.
mkdir laboratorio

# touch
# Cria um arquivo vazio.
touch arquivo.txt

# echo
# Cria um arquivo com conteúdo.
echo "Olá, Linux!" > mensagem.txt

# rm
# Remove um arquivo.
rm arquivo.txt

# rm -r
# Remove um diretório e seu conteúdo.
rm -r laboratorio

# ==========================================
# ATENÇÃO:
# rm não utiliza uma lixeira.
# Arquivos removidos podem não ser recuperáveis.
# ==========================================